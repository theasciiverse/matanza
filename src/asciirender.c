void
mat_asciirender_render ( MatScm *view, int x1, int y1, int x2, int y2, int wipe )
{
  int x, y;
  int val;
  int wi = mat_window_img_size_x_get(view);
  int pos, pos1;
  int i1, i2, i3, i4;
  float gamma;
  int *palette;
  unsigned char *imgbuffer;

  /* Here we check |x1|, |x2|, |y1| and |y2| and make sure they are inside the
   * screen. If they aren't, we fix them.
   *
   * Also, if they are attempting to render something outside of the screen, we
   * return. */

  if (x2 < 0 || y2 < 0)
    return;
  
  if (mat_window_chars_size_x_get(view) < x1 || mat_window_chars_size_y_get(view) < y1)
    return;

  if (x2 >= mat_window_chars_size_x_get(view))
    x2 = mat_window_chars_size_x_get(view);

  if (y2 >= mat_window_chars_size_y_get(view))
    y2 = mat_window_chars_size_y_get(view);

  if (x1 < 0)
    x1 = 0;

  if (y1 < 0)
    y1 = 0;

  x1 += mat_window_chars_pos_x_get(view);
  y1 += mat_window_chars_pos_y_get(view);
  x2 += mat_window_chars_pos_x_get(view);
  y2 += mat_window_chars_pos_y_get(view);

  if (mat_window_randomval_get(view) > 0)
    gamma = mat_window_randomval_get(view) / 2;
  else
    gamma = 0;

  palette = mat_window_palette_get(view);

  imgbuffer = mat_telnet_imgbuffer_get(view);

  for (y = y1; y < y2; y++)
    {
      pos = 2 * y * wi + x1 * 2;
      pos1 = y * mat_window_chars_size_x_get(view) + x1;
      for (x = x1; x < x2; x++)
        {
          /* We render four points in a square at a time.  In this section, we
           * get four points from |graph_imagebuffer| at position |pos| and
           * store their colors in |i1|, |i2|, |i3| and |i4|. */

          i1 = palette[(int)imgbuffer[pos         ]];
          i2 = palette[(int)imgbuffer[pos + 1     ]];
          i3 = palette[(int)imgbuffer[pos     + wi]];
          i4 = palette[(int)imgbuffer[pos + 1 + wi]];

          ASSERT(i1 >= 0);
          ASSERT(i2 >= 0);
          ASSERT(i3 >= 0);
          ASSERT(i4 >= 0);

          ASSERT(i1 < 256);
          ASSERT(i2 < 256);
          ASSERT(i3 < 256);
          ASSERT(i4 < 256);

#define MYLONG_MAX 0xffffffff
#define MYRAND() (((state * 1103515245) + 12345) & MYLONG_MAX)

          /* Apply the randomization to the points. */
          if (gamma)
            {
              static int state;

              state = MYRAND();

              i1 += (state >>  0) % mat_window_randomval_get(view) - gamma;
              i2 += (state >>  8) % mat_window_randomval_get(view) - gamma;
              i3 += (state >> 16) % mat_window_randomval_get(view) - gamma;
              i4 += (state >> 24) % mat_window_randomval_get(view) - gamma;

              /* Here we make sure the points have a color in the valid range.
               * This is optimized for the common case. */

              if ((i1 | i2 | i3 | i4) & (~255))
                {
                  if (i1 < 0)
                    i1 = 0;
                  else if (i1 > 255)
                    i1 = 255;
                  if (i2 < 0)
                    i2 = 0;
                  else if (i2 > 255)
                    i2 = 255;
                  if (i3 < 0)
                    i3 = 0;
                  else if (i3 > 255)
                    i3 = 255;
                  if (i4 < 0)
                    i4 = 0;
                  else if (i4 > 255)
                    i4 = 255;
                }
            }

          val = graph_table[((i1>>4)<<8)+((i2>>4)<<12) + ((i3>>4)<<0) + ((i4>>4)<<4)];

          if (wipe)
            {
              imgbuffer[pos         ] = 0;
              imgbuffer[pos + 1     ] = 0;
              imgbuffer[pos     + wi] = 0;
              imgbuffer[pos + 1 + wi] = 0;
            }

          mat_telnet_textbuffer_set(view, pos1, val & 0xff, val >> 8);

          pos += 2;
          pos1++;
        }
    }
}
