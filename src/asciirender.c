static void
fastscale(char *b1, char *b2, int x1, int x2, int y1, int y2, int width1, int width2, int color)
{
  int ddx1, ddx, spx = 0, ex;
  int ddy1, ddy, spy = 0, ey;
  int x;
  char *bb1 = b1;
  width2 -= x2;
  if (!x1 || !x2 || !y1 || !y2)
    return;
  ddx = x1 + x1;
  ddx1 = x2 + x2;
  if (ddx1 < ddx)
    spx = ddx / ddx1, ddx %= ddx1;
  ddy = y1 + y1;
  ddy1 = y2 + y2;
  if (ddy1 < ddy)
    spy = (ddy / ddy1) * width1, ddy %= ddy1;
  ey = -ddy1;
  for (; y2; y2--) {
    ex = -ddx1;
    for (x = x2; x; x--) {
      if (*b1)
        *b2 = color;
      b2++;
      b1 += spx;
      ex += ddx;
      if (ex > 0) {
        b1++;
        ex -= ddx1;
      }
    }
    b2 += width2;
    bb1 += spy;
    ey += ddy;
    if (ey > 0) {
      bb1 += width1;
      ey -= ddy1;
    }
    b1 = bb1;
  }
}

